#!/bin/sh

set -eu

repository_root=${1:-.}
repository_root=$(CDPATH= cd -- "$repository_root" && pwd)
go_image=${GO_IMAGE:?GO_IMAGE must be set}
oapi_codegen_version=${OAPI_CODEGEN_VERSION:?OAPI_CODEGEN_VERSION must be set}
oapi_codegen_runtime=${OAPI_CODEGEN_RUNTIME:-docker}
temporary_root=$(mktemp -d "${TMPDIR:-/tmp}/dify-agent-generated-check.XXXXXX")

cleanup() {
	rm -rf -- "$temporary_root"
}
trap cleanup EXIT HUP INT TERM

mkdir -p \
	"$temporary_root/api/openapi/v1" \
	"$temporary_root/generated/openapi/v1"
cp "$repository_root/api/openapi/v1/openapi.yaml" "$temporary_root/api/openapi/v1/openapi.yaml"
cp "$repository_root/api/openapi/v1/oapi-codegen.yaml" "$temporary_root/api/openapi/v1/oapi-codegen.yaml"

case "$oapi_codegen_runtime" in
	docker)
		docker run --rm \
			-v "$temporary_root:/src" \
			-w /src \
			"$go_image" \
			sh -c "go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@$oapi_codegen_version -config api/openapi/v1/oapi-codegen.yaml api/openapi/v1/openapi.yaml"
		;;
	local)
		(cd "$temporary_root" && go run "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@$oapi_codegen_version" -config api/openapi/v1/oapi-codegen.yaml api/openapi/v1/openapi.yaml)
		;;
	*)
		printf 'unsupported OAPI_CODEGEN_RUNTIME: %s\n' "$oapi_codegen_runtime" >&2
		exit 2
		;;
esac

if command -v sha256sum >/dev/null 2>&1; then
	contract_digest=$(sha256sum "$temporary_root/api/openapi/v1/openapi.yaml" | awk '{print $1}')
else
	contract_digest=$(shasum -a 256 "$temporary_root/api/openapi/v1/openapi.yaml" | awk '{print $1}')
fi
printf '%s\n' "$contract_digest" > "$temporary_root/api/openapi/v1/openapi.sha256"
{
	printf '%s\n' '// Code generated by make digest; DO NOT EDIT.'
	printf '%s\n\n' 'package openapiv1'
	printf 'const ContractSHA256 = "%s"\n' "$contract_digest"
} > "$temporary_root/generated/openapi/v1/digest.gen.go"

diff -ru \
	"$repository_root/generated/openapi/v1" \
	"$temporary_root/generated/openapi/v1"
diff -u \
	"$repository_root/api/openapi/v1/openapi.sha256" \
	"$temporary_root/api/openapi/v1/openapi.sha256"
