package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
)

const (
	migrationsDirectory  = "migrations"
	manifestPath         = "migrations/manifest.json"
	generatedVersionPath = "generated/migrations/version.gen.go"
)

var migrationNamePattern = regexp.MustCompile(`^([0-9]{6})_([a-z0-9]+(?:_[a-z0-9]+)*)\.(up|down)\.sql$`)

type manifest struct {
	SchemaVersion int              `json:"schemaVersion"`
	Policy        string           `json:"policy"`
	Migrations    []migrationEntry `json:"migrations"`
}

type migrationEntry struct {
	Version    int    `json:"version"`
	Name       string `json:"name"`
	Reversible bool   `json:"reversible"`
	UpSHA256   string `json:"upSHA256"`
	DownSHA256 string `json:"downSHA256,omitempty"`
}

func main() {
	writeVersion := flag.String("write-version", "", "write the generated migration version Go source")
	flag.Parse()
	if err := validateFiles(migrationsDirectory, manifestPath); err != nil {
		fmt.Fprintf(os.Stderr, "migration-manifest-check: %v\n", err)
		os.Exit(1)
	}
	manifestBytes, err := os.ReadFile(manifestPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "migration-manifest-check: read manifest version: %v\n", err)
		os.Exit(1)
	}
	version, err := latestVersion(manifestBytes)
	if err != nil {
		fmt.Fprintf(os.Stderr, "migration-manifest-check: %v\n", err)
		os.Exit(1)
	}
	expectedSource := generatedVersionSource(version)
	if *writeVersion != "" {
		if err := os.MkdirAll(filepath.Dir(*writeVersion), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "migration-manifest-check: create generated directory: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(*writeVersion, expectedSource, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "migration-manifest-check: write generated version: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("migration-manifest-check: wrote migration version %d\n", version)
		return
	}
	actualSource, err := os.ReadFile(generatedVersionPath)
	if err != nil || validateGeneratedVersion(expectedSource, actualSource) != nil {
		fmt.Fprintln(os.Stderr, "migration-manifest-check: generated migration version is missing or stale; run make migration-version")
		os.Exit(1)
	}
	fmt.Println("migration-manifest-check: append-only migration baseline is valid")
}

func validateGeneratedVersion(expected, actual []byte) error {
	if string(actual) != string(expected) {
		return errors.New("generated migration version is stale")
	}
	return nil
}

func latestVersion(manifestBytes []byte) (int, error) {
	var baseline manifest
	if err := json.Unmarshal(manifestBytes, &baseline); err != nil {
		return 0, fmt.Errorf("parse manifest version: %w", err)
	}
	if len(baseline.Migrations) == 0 {
		return 0, errors.New("migration manifest must contain at least one migration")
	}
	return baseline.Migrations[len(baseline.Migrations)-1].Version, nil
}

func generatedVersionSource(version int) []byte {
	return []byte(fmt.Sprintf("// Code generated by make migration-version; DO NOT EDIT.\npackage migrations\n\nconst ExpectedVersion uint = %d\n", version))
}

func validateFiles(directory, manifestFile string) error {
	manifestBytes, err := os.ReadFile(manifestFile)
	if err != nil {
		return fmt.Errorf("read manifest: %w", err)
	}
	entries, err := os.ReadDir(directory)
	if err != nil {
		return fmt.Errorf("read migration directory: %w", err)
	}
	files := make(map[string][]byte)
	for _, entry := range entries {
		if entry.IsDir() || entry.Name() == filepath.Base(manifestFile) {
			continue
		}
		contents, err := os.ReadFile(filepath.Join(directory, entry.Name()))
		if err != nil {
			return fmt.Errorf("read %s: %w", entry.Name(), err)
		}
		files[entry.Name()] = contents
	}
	return validate(manifestBytes, files)
}

func validate(manifestBytes []byte, files map[string][]byte) error {
	var baseline manifest
	if err := json.Unmarshal(manifestBytes, &baseline); err != nil {
		return fmt.Errorf("parse manifest: %w", err)
	}
	if baseline.SchemaVersion != 1 || baseline.Policy != "append-only" {
		return errors.New("manifest must declare schemaVersion 1 and append-only policy")
	}

	expectedFiles := make(map[string]string)
	lastVersion := 0
	for _, migration := range baseline.Migrations {
		if migration.Version != lastVersion+1 {
			return fmt.Errorf("migration versions must be contiguous: got %d after %d", migration.Version, lastVersion)
		}
		lastVersion = migration.Version
		prefix := fmt.Sprintf("%06d_%s", migration.Version, migration.Name)
		expectedFiles[prefix+".up.sql"] = migration.UpSHA256
		if migration.Reversible {
			if migration.DownSHA256 == "" {
				return fmt.Errorf("reversible migration %06d requires a down checksum", migration.Version)
			}
			expectedFiles[prefix+".down.sql"] = migration.DownSHA256
		} else if migration.DownSHA256 != "" {
			return fmt.Errorf("forward-only migration %06d must not declare a down checksum", migration.Version)
		}
	}

	for name, contents := range files {
		if !migrationNamePattern.MatchString(name) {
			return fmt.Errorf("invalid migration filename %s", name)
		}
		if len(contents) == 0 {
			return fmt.Errorf("migration %s is empty", name)
		}
		expected, ok := expectedFiles[name]
		if !ok {
			return fmt.Errorf("migration %s is not recorded in the append-only manifest", name)
		}
		actual := sha256.Sum256(contents)
		if hex.EncodeToString(actual[:]) != expected {
			return fmt.Errorf("published migration %s checksum changed", name)
		}
		delete(expectedFiles, name)
	}
	if len(expectedFiles) != 0 {
		missing := make([]string, 0, len(expectedFiles))
		for name := range expectedFiles {
			missing = append(missing, name)
		}
		sort.Strings(missing)
		return fmt.Errorf("manifest references missing migrations: %v", missing)
	}
	return nil
}
